def f(*v) -> str:
    out = []
    for x in np.ravel(np.array(v, dtype=float)):
        s = f"{x:.6g}"
        out.append("0" if s in ("-0", "0") else s)
    return " ".join(out)


def xyaxes(R: np.ndarray) -> str:
    return f(R[:, 0], R[:, 1])


