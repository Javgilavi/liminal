SCENES = {
    "tabletop_props": {"cubes", "cup", "bowl", "lidbox", "obstacle"},
    "grasp_test": {"cubes", "cup"},
    "obstacle_target": {"obstacle", "cubes"},
    "lid_box": {"lidbox", "cubes"},
}


def derived_block(geom: dict) -> str:
    lines = [DERIVED_MARKER, "derived:"]
    pos, R = head_camera_pose(geom)
    h = geom["cameras"]["head"]
    K = intrinsics(val(h["width"]), val(h["height"]), val(h["fovy_deg"]))
    lines += ["  head_camera_world:",
              f"    pos: [{f(pos).replace(' ', ', ')}]",
              f"    quat_mujoco: [{f(quat_from_mat(R)).replace(' ', ', ')}]",
              f"    quat_opencv: [{f(quat_from_mat(mujoco_to_opencv(R))).replace(' ', ', ')}]",
              f"    intrinsics: {{fx: {K['fx']:.2f}, fy: {K['fy']:.2f}, cx: {K['cx']:.1f}, cy: {K['cy']:.1f}}}"]
    for side in SIDES:
        p, Rw = wrist_camera_pose_in_gripper(side, geom)
        c = geom["cameras"][f"{side}_wrist"]
        K = intrinsics(val(c["width"]), val(c["height"]), val(c["fovy_deg"]))
        lines += [f"  {side}_wrist_camera_in_gripper:",
                  f"    pos: [{f(p).replace(' ', ', ')}]",
                  f"    quat_mujoco: [{f(quat_from_mat(Rw)).replace(' ', ', ')}]",
                  f"    quat_opencv: [{f(quat_from_mat(mujoco_to_opencv(Rw))).replace(' ', ', ')}]",
                  f"    intrinsics: {{fx: {K['fx']:.2f}, fy: {K['fy']:.2f}, cx: {K['cx']:.1f}, cy: {K['cy']:.1f}}}"]
    lines += ["  note: \"MJCF names: cameras head/left_wrist/right_wrist, sites left_ee/right_ee, bodies <side>_base and "
              "<side>_gripper, joints and actuators <side>_<joint>.\""]
    return "\n".join(lines) + "\n"


def write_derived(geom_path: Path, geom: dict) -> None:
    text = geom_path.read_text()
    if DERIVED_MARKER in text:
        text = text[: text.index(DERIVED_MARKER)]
    geom_path.write_text(text.rstrip("\n") + "\n\n" + derived_block(geom))


def main() -> None:
    geom_path = SIM_DIR / "station_geometry.yaml"
    geom = load_geometry(geom_path)
    (SIM_DIR / "model").mkdir(exist_ok=True)
    (SIM_DIR / "model" / "station_robot.xml").write_text(robot_include(geom))
    (SIM_DIR / "xlerobot_station.xml").write_text(scene("xlerobot_station", "../assets", "model/station_robot.xml", set(), geom))
    (SIM_DIR / "scenes").mkdir(exist_ok=True)
    for name, props in SCENES.items():
        (SIM_DIR / "scenes" / f"{name}.xml").write_text(scene(name, "../../assets", "../model/station_robot.xml", props, geom))
    write_derived(geom_path, geom)
    print("wrote model/station_robot.xml, xlerobot_station.xml, scenes/:", ", ".join(SCENES))


if __name__ == "__main__":
    main()
