def ring(name: str, radius: float, height: float, thick: float, n: int, z0: float, tilt: float, rgba: str,
         mass_each: float) -> str:
    """n boxes on a circle, forming the wall of a cup or bowl (tilt > 0 leans the wall outward)."""
    out = []
    seg = 2 * np.pi * radius / n * 0.62
    for i in range(n):
        a = 2 * np.pi * i / n
        r = radius + np.sin(tilt) * height / 2
        pos = (r * np.cos(a), r * np.sin(a), z0 + np.cos(tilt) * height / 2)
        # box local x = radial, y = tangential, z = up, then lean outward about the tangential axis
        Rz = np.array([[np.cos(a), -np.sin(a), 0], [np.sin(a), np.cos(a), 0], [0, 0, 1]])
        Ry = np.array([[np.cos(tilt), 0, np.sin(tilt)], [0, 1, 0], [-np.sin(tilt), 0, np.cos(tilt)]])
        q = quat_from_mat(Rz @ Ry)
        out.append(f'<geom name="{name}_wall{i}" type="box" pos="{f(pos)}" quat="{f(q)}" '
                   f'size="{f(thick / 2, seg, height / 2)}" rgba="{rgba}" mass="{mass_each:.4g}"/>')
    return "\n        ".join(out)


