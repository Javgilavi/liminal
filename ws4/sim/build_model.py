def arm_contacts(P: str) -> str:
    pairs = [("base", "shoulder"), ("base", "upper_arm"), ("shoulder", "lower_arm"), ("shoulder", "wrist"),
             ("upper_arm", "wrist"), ("lower_arm", "gripper"), ("wrist", "moving_jaw"), ("gripper", "moving_jaw"),
             ("shoulder", "torso"), ("base", "torso")]
    return "\n".join(f'<exclude body1="{P}{a}" body2="{P if b != "torso" else ""}{b}"/>' for a, b in pairs)


def arm_actuators(P: str, geom: dict) -> str:
    rng = val(geom["arms"]["joint_range_rad"])
    out = []
    for name in ("shoulder_pan", "shoulder_lift", "elbow_flex", "wrist_flex", "wrist_roll", "gripper"):
        tq = GRIPPER_TORQUE if name == "gripper" else STS3215["torque"]
        out.append(f'<position name="{P}{name}" joint="{P}{name}" class="sts3215" ctrlrange="{f(rng[name])}" '
                   f'forcerange="{f(-tq, tq)}"/>')
    return "\n".join(out)


